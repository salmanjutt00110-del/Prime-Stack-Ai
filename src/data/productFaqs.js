/**
 * Helper: Get FAQs for a product by matching against slug patterns
 * Tries exact match first, then partial match on base slug
 */
export function getProductFaqs(productId) {
  if (!productId) return [];
  
  // Exact match
  if (productFaqs[productId]) {
    return productFaqs[productId].faqs;
  }
  
  // Try matching base product name (e.g., "chatgpt-plus-1m" → try "chatgpt-plus")
  const baseParts = productId.split('-');
  for (let i = baseParts.length; i > 1; i--) {
    const partial = baseParts.slice(0, i).join('-');
    if (productFaqs[partial]) {
      return productFaqs[partial].faqs;
    }
  }
  
  return [];
}
