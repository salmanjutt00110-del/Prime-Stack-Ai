export function getBlogPostBySlug(slug) {
  if (!slug) return null;
  return blogPosts.find(p => p.slug === slug && p.published) || null;
}

export function getFeaturedBlogPosts() {
  return blogPosts.filter(p => p.featured && p.published);
}

export function getRelatedBlogPosts(currentId, relatedIds = []) {
  if (!relatedIds || relatedIds.length === 0) {
    return blogPosts.filter(p => p.id !== currentId && p.published).slice(0, 3);
  }
  return blogPosts.filter(p => relatedIds.includes(p.id) && p.id !== currentId && p.published).slice(0, 3);
}

export function getBlogPostsForProduct(productSlug) {
  if (!productSlug) return [];
  return blogPosts.filter(p => (p.relatedProductSlug === productSlug || productSlug.includes(p.relatedProductSlug?.split('-')[0])) && p.published).slice(0, 2);
}
